const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {validateData,escapeHTML,renderTopics,recordHTML}=require('./app.js');
const data=validateData(JSON.parse(fs.readFileSync(path.join(__dirname,'dados.json'),'utf8')));
assert.equal(data.items.length,85);assert.equal(data.questions.length,16);assert.equal(data.topics.length,8);
assert.equal(escapeHTML('<script>"&'),'&lt;script&gt;&quot;&amp;');
assert.throws(()=>validateData({...data,items:[...data.items,data.items[0]]}));
assert.throws(()=>validateData({...data,items:data.items.map((item,index)=>index?item:{...item,side:'bolsonaro-pl'})}));
assert.throws(()=>validateData({...data,sources:{...data.sources,bad:{label:'x',kind:'x',published:'2026',url:'javascript:alert(1)'}}}));
assert.throws(()=>validateData({...data,questions:[...data.questions,{...data.questions[0],id:'q-invalid',sources:['inexistente']}]}));
assert.throws(()=>validateData({...data,topics:data.topics.slice(1)}));
assert.throws(()=>validateData({...data,topics:data.topics.map((t,i)=>i?t:{...t,items:[...t.items,t.items[0]]})}));
const changeItem=(id,update)=>({...data,items:data.items.map(i=>i.id===id?{...i,...update}:i)});
assert.throws(()=>validateData(changeItem('lula-playboy-1979',{rightsAssessment:{level:5,reason:'x'}})));
assert.throws(()=>validateData(changeItem('jair-golpe-condenacao',{legalStatus:''})));
assert.throws(()=>validateData(changeItem('dilma-lbi-2015',{side:'bolsonaro-pl'})));
const html=renderTopics(data),ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(match=>match[1]);
assert.equal(ids.length,new Set(ids).size);
for(const item of data.items)assert.ok(ids.includes(item.id));
for(const q of data.questions)assert.ok(ids.includes(q.id));
assert.equal((html.match(/class="record"/g)||[]).length,85);
assert.equal((html.match(/class="rights-scale"/g)||[]).length,data.items.filter(i=>i.rightsAssessment).length);
assert.ok(!html.includes('prints recebidos'));assert.ok(!html.includes('bar-track'));
assert.ok(!data.topics.some(t=>t.id==='ditaduras'));
assert.ok(data.topics.find(t=>t.id==='instituicoes').items.includes('lula-playboy-1979'));
assert.ok(data.topics.find(t=>t.id==='instituicoes').items.includes('jair-golpe-condenacao'));
assert.ok(data.questions.find(q=>q.id==='q-lgbt-violencia').sources.includes('onu-discurso'));
assert.ok(!/[\u2013\u2014]/.test(JSON.stringify(data)));
const card=recordHTML(data,data.items.find(i=>i.id==='jair-fuzilar-2018'));
assert.ok(card.indexOf('<blockquote>')<card.indexOf('<details'));
assert.ok(card.includes('Defesa de violência'));
console.log('85 registros, 16 perguntas e 8 temas: autoria, fontes, situação processual, régua, falas visíveis e cobertura sem duplicações aprovados.');
