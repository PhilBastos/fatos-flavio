const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {selectItems,countStates,validateData,escapeHTML,recordHTML,renderMilitia,renderAnalysis,renderIndicators,renderQuestions}=require('./app.js');
const data=validateData(JSON.parse(fs.readFileSync(path.join(__dirname,'dados.json'),'utf8')));
assert.equal(data.items.length,31);
assert.equal(data.questions.length,12);
assert.deepEqual(countStates(data.items),{confirmado:26,'fora-de-contexto':1,'sem-prova':0,corrigido:4});
assert.equal(selectItems(data.items,{category:'milicias'}).length,4);
assert.equal(selectItems(data.items,{category:'milicias',kind:'Declaração'}).length,1);
assert.equal(selectItems(data.items,{person:'Jair Bolsonaro',category:'direitos',status:'corrigido'}).length,1);
assert.ok(selectItems(data.items,{q:'flavio'}).every(item=>item.person==='Flávio Bolsonaro'||JSON.stringify(item).toLowerCase().includes('flávio')));
assert.equal(selectItems(data.items,{status:'sem-prova'}).length,0);
assert.equal(selectItems(data.items,{q:'   '}).length,data.items.length);
assert.equal(escapeHTML('<script>"&'),'&lt;script&gt;&quot;&amp;');
assert.throws(()=>validateData({...data,items:[...data.items,data.items[0]]}));
assert.throws(()=>validateData({...data,items:data.items.map((item,index)=>index?item:{...item,side:'bolsonaro-pl'})}));
assert.throws(()=>validateData({...data,sources:{...data.sources,bad:{label:'x',kind:'x',published:'2026',url:'javascript:alert(1)'}}}));
assert.throws(()=>validateData({...data,questions:[...data.questions,{...data.questions[0],id:'q-invalid',sources:['inexistente']}]}));
assert.throws(()=>validateData({...data,indicators:{...data.indicators,series:[{year:2024,total:-1}]}}));
assert.throws(()=>validateData({...data,indicators:{...data.indicators,series:[{year:2024,total:1},{year:2024,total:2}]}}));
const html=data.items.flatMap(item=>[recordHTML(data,item),recordHTML(data,item,'placar-')]).join('')+renderQuestions(data)+renderMilitia(data)+renderAnalysis(data);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(match=>match[1]);
assert.equal(ids.length,new Set(ids).size);
assert.equal(data.indicators.series.find(row=>row.year===2022).total,7276);
assert.equal(data.indicators.series.find(row=>row.year===2024).total,10250);
assert.equal((renderIndicators(data,'bolsonaro').match(/class="bar-year"/g)||[]).length,4);
assert.equal((renderIndicators(data,'lula').match(/class="bar-year"/g)||[]).length,2);
assert.ok(renderMilitia(data).includes('não equivalem a uma condenação'));
assert.ok(renderAnalysis(data).includes('não é transferida'));
assert.ok(data.analysis.criteria.some(criterion=>criterion.items.includes('flavio-milicias-2007')));
assert.ok(!/[\u2013\u2014]/.test(JSON.stringify(data)));
console.log('31 registros e 12 perguntas: fontes, autoria, estados, filtros, indicadores, limites judiciais e IDs aprovados.');
